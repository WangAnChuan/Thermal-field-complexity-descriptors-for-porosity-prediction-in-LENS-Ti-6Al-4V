"""Figures added in revision: PTR forest and calibration curve.

The protocol schematic (Figure 1) is a hand-drawn SVG supplied with the
repository and is not generated by this script.
"""
import warnings
warnings.filterwarnings('ignore')
import numpy as np, pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.gridspec import GridSpec
from matplotlib.patches import Patch, Rectangle
import matplotlib as mpl
from figstyle import apply, panel as panel_head
from pathlib import Path

PAL = {'neutral': '#6E6E6E', 'neutral_light': '#B8B8B8', 'blue': '#0072B2',
       'vermillion': '#D55E00', 'green': '#009E73', 'ink': '#222222', 'grey': '#8C8C8C'}
apply()
OUT = Path('figures'); OUT.mkdir(exist_ok=True)
W = 5.42

def save(fig, stem):
    fig.savefig(OUT / f'{stem}.svg', bbox_inches='tight', pad_inches=0.02)
    fig.savefig(OUT / f'{stem}.pdf', bbox_inches='tight', pad_inches=0.02)
    fig.savefig(OUT / f'{stem}.png', bbox_inches='tight', pad_inches=0.02, dpi=600)
    print(f'saved {stem}.svg/.pdf/.png')

def panel_label(ax, text, x=-0.10, y=1.10):
    ax.text(x, y, text, transform=ax.transAxes, fontsize=8, weight='bold',
            va='bottom', ha='left', color=PAL['ink'])

# ---------------------------------------------------------------- protocol schematic
# Figure 1 is hand-drawn and supplied as figures/fig_protocol_schematic.svg;
# it is converted to PDF for the manuscript and is not generated here.


# ---------------------------------------------------------------- PTR forest
rows = [
    ('Complexity (3) · CatBoost',        2.51, 1.64,  4.95, True,  '2.51'),
    ('Complexity (3) · XGBoost',         1.33, 0.81,  2.85, True,  '1.33'),
    ('Gradients (2) · CatBoost',         3.51, 1.38, 26.76, True,  '3.51'),
    ('Entropy (1) · CatBoost',           1.48, 0.82,  3.10, True,  '1.48'),
    ('Entropy (1) · XGBoost',            1.19, 0.73,  2.55, True,  '1.19'),
    ('Moments (3) · CatBoost',           5.71, None,  None, False, 'n.d.'),
    ('Random projections (3) · CatBoost', 2.74, None, None, False, 'n.d.'),
    ('Permuted (3) · CatBoost',          None, None,  None, False, '≤ 0'),
]
fig, ax = plt.subplots(figsize=(W * 0.80, 2.55))
y = np.arange(len(rows))[::-1]
for i, (label, ptr, lo, hi, ok, txt) in enumerate(rows):
    c = PAL['blue'] if 'CatBoost' in label and ok else (PAL['vermillion'] if ok else PAL['neutral'])
    if ok:
        ax.plot([lo, hi], [y[i], y[i]], lw=1.0, color=c, solid_capstyle='butt')
        ax.plot(ptr, y[i], 'o', ms=4.5, color=c, mec='white', mew=0.4, zorder=3)
        ax.text(hi * 1.15, y[i], txt, fontsize=6.0, va='center', color=c)
    elif ptr is not None:
        ax.plot(ptr, y[i], 'o', ms=4.5, mfc='white', mec=PAL['neutral'], mew=0.9, zorder=3)
        ax.text(ptr * 1.22, y[i], txt, fontsize=5.8, va='center', color=PAL['neutral'])
    else:
        ax.text(2.2, y[i], txt, fontsize=5.8, va='center', ha='center', color=PAL['neutral'])
ax.axhline(2.5, color='#DDDDDD', lw=0.6)
ax.axvline(1.0, color=PAL['grey'], lw=0.8, ls=(0, (2, 2)))
ax.set_xscale('log')
ax.set_xlim(0.5, 45)
ax.set_xticks([0.5, 1, 2, 5, 10, 20]); ax.set_xticklabels(['0.5', '1', '2', '5', '10', '20'])
ax.minorticks_off()
ax.set_yticks(y); ax.set_yticklabels([r[0] for r in rows], fontsize=6.0)
ax.set_xlabel('Protocol transfer ratio (log scale)', fontsize=7.0)
ax.text(1.06, -0.75, 'no transfer', fontsize=5.8, color=PAL['neutral'], va='center')
ax.set_ylim(-1.0, len(rows) - 0.4)
for sp in ['top', 'right']: ax.spines[sp].set_visible(False)
panel_head(ax, None, 'Protocol transfer ratio', x=-0.62, y=1.02)
save(fig, 'fig_ptr_forest'); plt.close(fig)

# ---------------------------------------------------------------- calibration
cal = pd.read_csv('results/results_ptr_calibration.csv')
g = cal.groupby('omega').ptr.agg(['mean', 'std', 'count']).reset_index()
fig, ax = plt.subplots(figsize=(W * 0.72, 2.05))
ax.errorbar(g.omega, g['mean'], yerr=g['std'], fmt='o-', ms=3.6, lw=0.9,
            color=PAL['green'], ecolor=PAL['green'], elinewidth=0.7, capsize=2, capthick=0.6)
ax.plot([0.8, 5.2], [0.8, 5.2], ls=':', lw=0.7, color=PAL['grey'])
ax.text(4.6, 4.6, 'identity', fontsize=5.8, color=PAL['neutral'], ha='right', va='bottom')
ax.set_xscale('log'); ax.set_yscale('log')
ax.set_xticks([1, 2, 3, 5]); ax.set_xticklabels(['1', '2', '3', '5'])
ax.set_yticks([1, 2, 3, 5]); ax.set_yticklabels(['1', '2', '3', '5'])
ax.minorticks_off()
ax.set_xlim(0.85, 5.5); ax.set_ylim(0.85, 5.5)
ax.set(xlabel='True effect growth factor', ylabel='Estimated PTR')
panel_head(ax, None, 'Synthetic calibration', x=-0.28, y=1.03)
ax.text(5.4, 1.95, 'PTR rises only to 1.11\nfor a five-fold effect', fontsize=6.0, color=PAL['neutral'],
        ha='right', va='center')
save(fig, 'fig_calibration'); plt.close(fig)
print('additions done')
